/*
 * What both user modules (texthook.prx and thkpopup.prx) share: reading the
 * core's captured text, the game's script (its filters), decoding to
 * UTF-8, and the log.
 */

#ifndef SHARED_H
#define SHARED_H

#include "texthook.h"
#include "thk_abi.h"

/*
 * Everything the modules allocate (thread stacks, buffers) comes from the
 * volatile memory they run in, so games keep all of their user memory.
 */
#define TH_PARTITION    5

/* Worst case UTF-16 -> UTF-8. */
#define TH_LINE_MAX     (TH_MAX_TEXT * 3 / 2 + 1)

/* One captured string, as the core keeps it (thk_event), with room for its data. */
typedef struct th_event {
    u16  len;           /* bytes in data */
    u8   hook;
    u8   enc;           /* THK_ENC_* */
    u8   data[TH_MAX_TEXT];
} th_event;

/* --- script.c: the game's script, and its filters ------------------------ */

extern const th_game *const th_games[];     /* generated by the Makefile */
extern const th_game        *th_current_game;

const th_game *th_find_game(const char *id);

/* Event `seq` from the core, decoded and filtered: the line's length, or < 0. */
int th_event_line(u32 seq, char *out, int size, int *hook);

/* --- text.c: decoding ---------------------------------------------------- */

/* Converts an event to NUL-terminated UTF-8. Returns the length. */
int th_to_utf8(const th_event *ev, char *out, int outsize);
u32 th_hash(const char *s, int len);
int th_put_utf8(char *out, u32 cp);                 /* writes 1-4 bytes, returns how many */
u32 th_next_utf8(const char **s);                   /* decodes one code point, 0 at the end */
void th_text_free(void);    /* the module is stopping */

/* --- log.c --------------------------------------------------------------- */

extern const char th_log_name[];       /* "user", "popup": each module's own */

void th_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

#endif /* SHARED_H */
